/* Eye-catch score for the 10 FreshDrop ads. Reproducible:
   1) serve the repo (python3 -m http.server 8777)  2) npm i puppeteer-core
   3) node tools/score-ads.js http://127.0.0.1:8777/ /path/to/chrome
   Writes ads/freshdrop/scores.js and ads/freshdrop/png/ad-N.png */
const puppeteer=require('puppeteer-core'),fs=require('fs'),path=require('path');
const BASE=process.argv[2]||'http://127.0.0.1:8777/',CHROME=process.argv[3]||'/usr/bin/google-chrome';
(async()=>{
const b=await puppeteer.launch({executablePath:CHROME,args:['--no-sandbox']});const pg=await b.newPage();
await pg.evaluateOnNewDocument(()=>{window.FD_SCORES=null});
await pg.goto(BASE+'ads/freshdrop/?score=1',{waitUntil:'networkidle0'});await pg.waitForFunction('window.FD_READY===true');
const res=await pg.evaluate(()=>{
 function lin(v){v/=255;return v<=.03928?v/12.92:Math.pow((v+.055)/1.055,2.4)}
 function L(r,g,b){return .2126*lin(r)+.7152*lin(g)+.0722*lin(b)}
 function cr(a,b){var h=Math.max(a,b),l=Math.min(a,b);return (h+.05)/(l+.05)}
 function hex(h){var n=parseInt(h.slice(1),16);return [n>>16,n>>8&255,n&255]}
 return FD_ADS.map(function(a,i){
  var c=document.querySelector('canvas[data-i="'+i+'"]'),W=1080,d=c.getContext('2d').getImageData(0,0,W,W).data,png=c.toDataURL('image/png');
  var S=4,n=0,sRg=0,sYb=0,qRg=0,qYb=0,hist={},lum=[],edges=0,cta=0,acc=hex(a.acc);
  var G=new Float32Array((W/S)*(W/S));
  for(var y=0;y<W;y+=S)for(var x=0;x<W;x+=S){var k=(y*W+x)*4,r=d[k],g=d[k+1],bb=d[k+2];
    var rg=r-g,yb=.5*(r+g)-bb;sRg+=rg;sYb+=yb;qRg+=rg*rg;qYb+=yb*yb;n++;
    var key=(r>>4)+','+(g>>4)+','+(bb>>4);hist[key]=(hist[key]||0)+1;var l=L(r,g,bb);lum.push(l);G[(y/S)*(W/S)+x/S]=l;
    if(Math.abs(r-acc[0])<28&&Math.abs(g-acc[1])<28&&Math.abs(bb-acc[2])<28)cta++;}
  var mRg=sRg/n,mYb=sYb/n,sdRg=Math.sqrt(qRg/n-mRg*mRg),sdYb=Math.sqrt(qYb/n-mYb*mYb);
  var colourful=Math.sqrt(sdRg*sdRg+sdYb*sdYb)+.3*Math.sqrt(mRg*mRg+mYb*mYb);
  var top=Object.keys(hist).sort(function(p,q){return hist[q]-hist[p]})[0].split(',').map(function(v){return v*16+8});
  var bgL=L(top[0],top[1],top[2]);
  lum.sort(function(p,q){return p-q});var p5=lum[Math.floor(lum.length*.05)],p95=lum[Math.floor(lum.length*.95)];
  var contrast=cr(p5,p95);
  var w=W/S;for(var yy=1;yy<w-1;yy++)for(var xx=1;xx<w-1;xx++){var gx=G[yy*w+xx+1]-G[yy*w+xx-1],gy=G[(yy+1)*w+xx]-G[(yy-1)*w+xx];if(Math.sqrt(gx*gx+gy*gy)>.08)edges++}
  var edgeD=edges/((w-2)*(w-2)),ctaArea=cta/n,ctaC=cr(L(acc[0],acc[1],acc[2]),bgL);
  var sCol=Math.min(colourful/100,1),sCon=Math.min((contrast-1)/20,1),sCta=.5*Math.min((ctaC-1)/6,1)+.5*Math.min(ctaArea/.04,1),sEdge=Math.max(0,1-Math.abs(edgeD-.12)/.12);
  var total=100*(.35*sCol+.25*sCon+.25*sCta+.15*sEdge);
  return {i:i,site:a.site,png:png,m:{colourfulness:+colourful.toFixed(1),contrast:+contrast.toFixed(2),ctaContrast:+ctaC.toFixed(2),ctaArea:+(ctaArea*100).toFixed(2),edgeDensity:+(edgeD*100).toFixed(2)},
    parts:{colour:+(sCol*100).toFixed(1),contrast:+(sCon*100).toFixed(1),cta:+(sCta*100).toFixed(1),edges:+(sEdge*100).toFixed(1)},total:+total.toFixed(2)};});});
await b.close();
const dir=path.join(__dirname,'..','ads','freshdrop');fs.mkdirSync(path.join(dir,'png'),{recursive:true});
const scores={};res.forEach(r=>{fs.writeFileSync(path.join(dir,'png','ad-'+(r.i+1)+'.png'),Buffer.from(r.png.split(',')[1],'base64'));delete r.png;scores[r.i]=r});
const order=res.slice().sort((a,b)=>b.total-a.total).map(r=>r.i);
fs.writeFileSync(path.join(dir,'scores.js'),'/* Generated by tools/score-ads.js - do not edit */\nwindow.FD_SCORES='+JSON.stringify({order,scores},null,1)+';\n');
order.forEach((i,k)=>console.log(k+1,scores[i].site,scores[i].total,JSON.stringify(scores[i].m)));
})();
